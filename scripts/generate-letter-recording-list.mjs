/**
 * Regenerates docs/letter-recordings.md from the letter table in
 * client/src/lib/arabicLetters.ts, so the list handed to the reciter always
 * matches the filenames the app actually requests.
 *
 *   node scripts/generate-letter-recording-list.mjs
 *
 * server/letterRecordings.test.ts fails if the committed doc has drifted.
 */
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const source = fs.readFileSync(path.join(root, "client/src/lib/arabicLetters.ts"), "utf-8");

// The module is TypeScript, so parse the literal rather than importing it.
const letters = [...source.matchAll(
  /\{ letter: "(.+?)", name: "(.+?)", slug: "(.+?)", transliteration: "(.+?)", sound: "(.+?)" \}/g,
)].map(([, letter, name, slug, transliteration, sound]) => ({ letter, name, slug, transliteration, sound }));

if (letters.length !== 28) {
  throw new Error(`Expected 28 letters in arabicLetters.ts, found ${letters.length}`);
}

const HARAKAT = [
  { id: "fatha", label: "Fatha", mark: "َ", hint: "short a" },
  { id: "kasra", label: "Kasra", mark: "ِ", hint: "short i" },
  { id: "damma", label: "Damma", mark: "ُ", hint: "short u" },
];

const rows = [];
for (const entry of letters) {
  rows.push(`| \`${entry.slug}.mp3\` | ${entry.letter} | ${entry.name} (${entry.transliteration}) | the letter on its own |`);
  for (const harakat of HARAKAT) {
    rows.push(`| \`${entry.slug}-${harakat.id}.mp3\` | ${entry.letter}${harakat.mark} | ${entry.name} + ${harakat.label} | ${harakat.hint} |`);
  }
}

const doc = `# Letter recordings needed

<!-- Generated by scripts/generate-letter-recording-list.mjs — edit that, not this. -->

**${rows.length} recordings**: each of the 28 Arabic letters on its own, and
carrying each of the three short vowels.

These replace the app's previous use of English speech synthesis, which produced
the wrong sounds — "Taa" came out as "Te AA", and letters such as ح ع ص ض ط ظ ق غ
have no English phoneme at all. Until a file is delivered, the app tells the
learner the recording is unavailable rather than approximating it.

## How to record

- One letter per file, nothing else on the recording — no introduction, no
  English, no phrase around it.
- Say the letter's **sound**, not its alphabet name: \`ba.mp3\` is the sound
  *b*, not the word "bāʾ".
- For the harakat files, say the letter carrying that vowel: \`ba-fatha.mp3\`
  is *ba*, \`ba-kasra.mp3\` is *bi*, \`ba-damma.mp3\` is *bu*.
- Keep a natural, unhurried pace, as when teaching a beginner.
- MP3, mono is fine, 128 kbps or better, 44.1 kHz.
- Trim silence at both ends, leaving roughly 100 ms of head and tail.
- Keep the level consistent across all ${rows.length} files so one letter is not
  noticeably louder than the next.

## Naming

Use the filename in the first column exactly — lowercase, no spaces. The slugs
are fixed because several letters share a display name in English (ت and ط are
both "Taa"; ح and ه are both "Haa"), so the filename is what keeps them apart.

**Please double-check these pairs**, where a mix-up would teach the wrong
letter: ت \`ta\` / ط \`tta\` · س \`seen\` / ص \`sad\` · د \`dal\` / ض \`dad\` ·
ز \`zay\` / ظ \`zza\` / ذ \`dhal\` · ه \`ha\` (soft) / ح \`hha\` (deep).

## Where the files go

\`client/public/audio/letters/\`. The app is playing temporary stand-in audio
until the set is delivered; switching over to these files is a one-line change
in \`client/src/lib/letterAudioSources.ts\`, described in that directory's
README.

## The list

| File | Sound | Letter | Notes |
| ---- | ----- | ------ | ----- |
${rows.join("\n")}
`;

fs.writeFileSync(path.join(root, "docs/letter-recordings.md"), doc, "utf-8");
console.log(`Wrote docs/letter-recordings.md with ${rows.length} recordings`);
