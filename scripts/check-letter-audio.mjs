/**
 * Checks that every clip the Starter lesson asks for actually exists.
 *
 *   node scripts/check-letter-audio.mjs
 *
 * Both letter-audio sources are local files under the same names, so this is a
 * filesystem check: 112 files, none of them empty. It also reports which of
 * them are still machine-generated, by reading the manifest the generator
 * writes — that is the difference between "the lesson has audio" and "the
 * lesson has a reciter".
 *
 * Exits non-zero if anything is missing or empty, so it can gate a deploy.
 */
import fs from "node:fs";
import path from "node:path";
import { ROOT, everyRecording } from "./letterTable.mjs";

const source = fs.readFileSync(path.join(ROOT, "client/src/lib/letterAudioSources.ts"), "utf-8");
const activeId = source.match(/ACTIVE_LETTER_AUDIO_SOURCE: LetterAudioSource = (\w+)/)?.[1] ?? "unknown";

const dir = path.join(ROOT, "client/public/audio/letters");
const manifestPath = path.join(dir, "generated.json");
const manifest = fs.existsSync(manifestPath) ? JSON.parse(fs.readFileSync(manifestPath, "utf-8")) : null;
const generated = new Set(Object.keys(manifest?.clips ?? {}));

console.log(`Active source: ${activeId}`);
console.log(`Directory:     ${path.relative(ROOT, dir)}/`);
if (manifest) console.log(`Manifest:      ${generated.size} clip(s) generated by ${manifest.model} / ${manifest.voice}`);
console.log("");

const results = everyRecording().map(({ file }) => {
  const full = path.join(dir, file);
  const bytes = fs.existsSync(full) ? fs.statSync(full).size : null;
  return { file, bytes, ok: bytes !== null && bytes > 0, synthesised: generated.has(file) };
});

const bad = results.filter((result) => !result.ok);
for (const result of bad) {
  console.log(`FAIL ${result.file.padEnd(18)} ${result.bytes === null ? "missing" : "empty"}`);
}

const synthesised = results.filter((result) => result.ok && result.synthesised).length;
const recorded = results.length - bad.length - synthesised;

console.log(`${results.length - bad.length}/${results.length} present.`);
if (synthesised) console.log(`${synthesised} synthesised, ${recorded} recorded.`);

if (bad.length) {
  console.log("\nGenerate the missing clips:\n");
  console.log(`  OPENAI_API_KEY=sk-... node scripts/generate-letter-audio.mjs --only=${
    [...new Set(bad.map((result) => result.file.replace(/(-\w+)?\.mp3$/, "")))].join(",")
  }`);
  console.log("\nor drop the reciter's recordings in under the same names — see");
  console.log("client/public/audio/letters/README.md.");
}

process.exit(bad.length ? 1 : 0);
